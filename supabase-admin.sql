-- Carewell doctor availability administration.
-- Run in Supabase SQL Editor after confirming the admin auth user exists.
create table if not exists public.doctors (
  id bigint generated by default as identity primary key,
  full_name text not null unique,
  department text not null,
  specialty text not null,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.hospital_admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.doctor_availability (
  id bigint generated by default as identity primary key,
  doctor_id bigint not null references public.doctors(id) on delete cascade,
  day_of_week smallint not null check (day_of_week between 0 and 6),
  start_time time not null default '09:00',
  end_time time not null default '17:00',
  status text not null default 'Available' check (status in ('Available','Unavailable')),
  note text,
  updated_by uuid references auth.users(id) on delete set null,
  updated_at timestamptz not null default now(),
  unique (doctor_id, day_of_week),
  check (status = 'Unavailable' or end_time > start_time)
);

create or replace function public.is_hospital_admin()
returns boolean
language sql stable security definer
set search_path = public
as $$
  select exists (select 1 from public.hospital_admins where user_id = auth.uid());
$$;
revoke all on function public.is_hospital_admin() from public;
grant execute on function public.is_hospital_admin() to authenticated;

alter table public.doctors enable row level security;
alter table public.hospital_admins enable row level security;
alter table public.doctor_availability enable row level security;

drop policy if exists "Authenticated staff can read doctors" on public.doctors;
create policy "Authenticated staff can read doctors" on public.doctors for select to authenticated using (true);
drop policy if exists "Admins manage doctors" on public.doctors;
create policy "Admins manage doctors" on public.doctors for all to authenticated using (public.is_hospital_admin()) with check (public.is_hospital_admin());
drop policy if exists "Admins can read admin list" on public.hospital_admins;
create policy "Admins can read admin list" on public.hospital_admins for select to authenticated using (user_id = auth.uid());
drop policy if exists "Authenticated staff can read availability" on public.doctor_availability;
create policy "Authenticated staff can read availability" on public.doctor_availability for select to authenticated using (true);
drop policy if exists "Admins manage availability" on public.doctor_availability;
create policy "Admins manage availability" on public.doctor_availability for all to authenticated using (public.is_hospital_admin()) with check (public.is_hospital_admin());

grant select on public.doctors, public.doctor_availability to authenticated;
grant insert, update, delete on public.doctors, public.doctor_availability to authenticated;
grant usage, select on all sequences in schema public to authenticated;

